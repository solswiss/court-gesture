import { validAppearance } from '../src/appearance';
import assert from 'node:assert/strict';
import { COURT, SIM_DT } from '../src/config';
import { CpuController } from '../src/input/cpu';
import { makeRng } from '../src/rng';
import { Game } from '../src/sim/game';
import { emptyInput } from '../src/types';
import { controlledPlayerId, isSnapshot, applySnapshot, RemoteController, sanitizeInput, SlotController, snapshot, SnapshotBuffer } from '../src/net/state';

const idle = { update: emptyInput };
const game = new Game([idle, idle]);
const replica = new Game([idle, idle]);
game.phase = 'rally';
game.ball.pos.x = 2;
const first = snapshot(game, 1);
const wire = JSON.parse(JSON.stringify(first));
assert.ok(isSnapshot(wire, 2));
assert.equal(isSnapshot({ ...wire, server: 42 }, 2), false);
assert.equal(isSnapshot({ ...wire, ball: { ...wire.ball, pos: { x: NaN, y: 0, z: 0 } } }, 2), false);
assert.equal(isSnapshot({ ...wire, events: [{ kind: 'hit' }] }, 2), false);
applySnapshot(replica, wire);
assert.deepEqual(snapshot(replica, 1), first);
replica.ball.pos.x = 9;
assert.equal(first.ball.pos.x, 2, 'snapshots do not share live references');
const buffer = new SnapshotBuffer();
assert.ok(buffer.push(first, 1000));
game.ball.pos.x = 6;
game.players[0].pos.x = 4;
const second = snapshot(game, 2, [{ kind: 'net' }]);
assert.ok(buffer.push(second, 1040));
assert.equal(buffer.push(first, 1050), false, 'ignore stale snapshots');
buffer.render(replica, 1120);
assert.equal(replica.ball.pos.x, 4, 'interpolate ball halfway');
assert.equal(replica.players[0].pos.x, 2, 'interpolate player halfway');
assert.equal(buffer.takeEvents().length, 0, 'events wait for display time');
buffer.render(replica, 1140);
assert.deepEqual(buffer.takeEvents(), [{ kind: 'net' }]);
assert.deepEqual(buffer.takeEvents(), [], 'events fire only once');
game.hitSerial++;
game.ball.pos.x = -8;
buffer.push(snapshot(game, 3), 1080);
buffer.render(replica, 1160);
assert.equal(replica.ball.pos.x, 6, 'do not interpolate across contact');
buffer.render(replica, 1180);
assert.equal(replica.ball.pos.x, -8);

assert.equal(sanitizeInput({ ...emptyInput(), moveX: NaN }), undefined);
assert.equal(sanitizeInput({ ...emptyInput(), action: 'cheat' }), undefined);
assert.equal(sanitizeInput({ ...emptyInput(), aim: null }), undefined);
assert.equal(sanitizeInput({ ...emptyInput(), moveX: 20 })?.moveX, 1);
const remote = new RemoteController();
const input = { ...emptyInput(), action: 'bump' as const, moveX: 1 };
assert.ok(remote.receive(1, input, performance.now()));
assert.equal(remote.receive(1, input, performance.now()), false);
assert.equal(remote.update().action, 'bump');
assert.equal(remote.update().action, null, 'action consumed once');
assert.equal(remote.update().moveX, 1, 'movement held across ticks');
remote.receive(2, input, performance.now() - 1000);
assert.deepEqual(remote.update(), emptyInput(), 'stale input becomes neutral');
const slot = new SlotController({ update: () => ({ ...emptyInput(), moveX: -1 }) });
slot.human = { update: () => ({ ...emptyInput(), moveX: 1 }) };
assert.equal(slot.update(SIM_DT, game, game.players[0]).moveX, 1);
slot.human = undefined;
assert.equal(slot.update(SIM_DT, game, game.players[0]).moveX, -1, 'CPU resumes after disconnect');

const four = new Game([idle, idle, idle, idle]);
const teamSlots = Array.from({ length: 4 }, () => new SlotController({ update: () => ({ ...emptyInput(), action: 'spike', moveX: -1 }) }));
const turns = new Game(teamSlots);
for (const s of teamSlots) s.teamSlots = teamSlots;
const driven: number[] = [];
teamSlots[0].human = { update: (_dt, _g, p) => { driven.push(p.id); return { ...emptyInput(), moveX: 1 }; }, sampleContactAim: () => ({ x: 0.7, d: 0, power: 1 }) };
turns.phase = 'rally';
const stepSlots = () => teamSlots.map((s, i) => s.update(SIM_DT, turns, turns.players[i]));
let inputs = stepSlots();
assert.deepEqual(driven.splice(0), [0]);
assert.equal(inputs[2].action, null, 'waiting teammate cannot hit automatically');
turns.players[0].lastTouchTime = 1;
turns.lastTouchSide = 1;
turns.players[0].pending = { type: 'bump', age: 0 };
inputs = stepSlots();
assert.deepEqual(driven.splice(0), [2], 'control switches after the first teammate hits');
assert.equal(turns.players[0].pending, null, 'clear the waiting player’s queued action');
assert.equal(inputs[0].action, null);
assert.ok(inputs[2].moveX < 0, 'active teammate runs toward the ball instead of repeating manual movement');
assert.equal(teamSlots[2].sampleContactAim()?.x, 0.7, 'contact aim follows the human onto the teammate');
turns.players[1].lastTouchTime = 2;
assert.equal(controlledPlayerId(turns, [true, false, false, false], 0), 2, 'the next team touch stays with the waiting teammate');
turns.players[2].lastTouchTime = 3;
stepSlots();
assert.deepEqual(driven.splice(0), [0], 'control switches back after the second teammate hits');
teamSlots[2].human = idle;
assert.equal(controlledPlayerId(turns, [true, false, true, false], 0), 0, 'two human teammates retain individual controls');
assert.equal(controlledPlayerId(turns, [true, false, true, false], 2), 2);
turns.restart();
assert.equal(controlledPlayerId(turns, [true, false, false, false], 0), 0, 'a new serve resets control to the server');
assert.equal(controlledPlayerId(turns, [true, true, false, false], 1), 1, 'receiving team starts with its owner');
teamSlots[2].human = undefined;
turns.phase = 'rally';
turns.lastTouchSide = -1;
turns.ball.pos = { x: 2.5, y: 4, z: -2 };
turns.ball.vel = { x: 0, y: 2, z: 7 };
turns.players[0].teleport(-3, 6);
turns.players[2].teleport(2.5, 4);
assert.equal(controlledPlayerId(turns, [true, false, false, false], 0), 2, 'nearest avatar to the landing zone receives');
turns.players[0].teleport(2.5, 4);
turns.players[2].teleport(-3, 6);
assert.equal(controlledPlayerId(turns, [true, false, false, false], 0), 2, 'receiver stays committed while players move');
turns.hitSerial++;
assert.equal(controlledPlayerId(turns, [true, false, false, false], 0), 0, 'a new return selects the newly closest avatar');

// Hold a ball above our court to isolate positioning over many simulation steps.
turns.lastTouchSide = 1;
turns.touchCount = 1;
turns.players[0].lastTouchTime = turns.time;
turns.ball.pos = { x: -3, y: 4, z: 2 };
turns.ball.vel = { x: 0, y: 0, z: 0 };
turns.ball.mode = 'held';
turns.players[0].teleport(-1.8, 3.5);
turns.players[2].teleport(1.8, 3.5);
for (let tick = 0; tick < 600; tick++) {
  turns.update(SIM_DT);
  for (const p of [turns.players[0], turns.players[2]]) {
    assert.ok(Math.abs(p.pos.x) < COURT.halfW && p.pos.z > 0 && p.pos.z < COURT.halfLen, 'both shared avatars stay on court');
  }
}
assert.ok(Math.abs(turns.players[2].pos.x + 3) < 0.2, 'next hitter approaches the ball automatically with no camera');
assert.ok(Math.abs(turns.players[0].pos.x + 1.8) < 0.2, 'waiting teammate holds its coverage position');
assert.equal(turns.hitSerial, 1, 'waiting teammate never generates CPU hits');
turns.ball.pos = { x: 20, y: 4, z: 20 };
for (let tick = 0; tick < 600; tick++) turns.update(SIM_DT);
assert.ok(turns.players[2].pos.x < COURT.halfW && turns.players[2].pos.z < COURT.halfLen, 'auto movement targets stay inside court for out balls');
turns.ball.pos = { x: 0, y: 4, z: -4 };
for (let tick = 0; tick < 600; tick++) turns.update(SIM_DT);
assert.ok(Math.abs(turns.players[2].pos.x - 1.8) < 0.2 && Math.abs(turns.players[2].pos.z - 3.5) < 0.2, 'both avatars cover when the ball is headed to the other side');
assert.deepEqual(four.players.map(p => p.side), [1, -1, 1, -1]);
assert.notEqual(four.players[0].pos.x, four.players[2].pos.x);
four.phase = 'rally';
four.players[0].teleport(0, 4);
four.players[2].teleport(0, 4);
four.players[0].pending = { type: 'bump', age: 0 };
four.players[2].pending = { type: 'bump', age: 0 };
four.ball.pos = { x: 0, y: 1.5, z: 3.55 };
four.update(SIM_DT);
assert.equal(four.hitSerial, 1, 'overlapping teammates do not double-hit');
four.restart();
assert.ok(four.players.every(p => p.pending === null));
const copy = new Game([idle, idle, idle, idle]);
applySnapshot(copy, JSON.parse(JSON.stringify(snapshot(four, 4))));
assert.equal(copy.players.length, 4);
assert.equal(copy.server.id, four.server.id);
let points = 0;
const teamGame = new Game(Array.from({ length: 4 }, (_, i) => new CpuController('normal', makeRng(i + 50))), 50);
for (let tick = 0; tick < 120 * 180; tick++) {
  teamGame.update(SIM_DT);
  assert.ok(Number.isFinite(teamGame.ball.pos.x + teamGame.ball.pos.y + teamGame.ball.pos.z));
  points += teamGame.drainEvents().filter(e => e.kind === 'point').length;
  if (teamGame.phase === 'over') teamGame.restart();
}
assert.ok(points > 0, '2v2 CPU match makes progress');
console.log(`Network, interpolation, slot takeover and 2v2 checks passed (${points} points in three simulated minutes)`);

assert.ok(validAppearance({ color: 0x9944ff, pantsColor: 0xffffff, pants: 'boardshorts' }));
assert.equal(validAppearance({ color: -1, pantsColor: 0, pants: 'shorts' }), false);
assert.equal(validAppearance({ color: 0, pantsColor: 0, pants: 'invalid' }), false);
Object.assign(game.players[0], { color: 0x9944ff, pantsColor: 0x11aabb, pants: 'boardshorts' });
const outfit = JSON.parse(JSON.stringify(snapshot(game, 99)));
assert.ok(isSnapshot(outfit, 2));
applySnapshot(replica, outfit);
assert.equal(replica.players[0].color, 0x9944ff);
assert.equal(replica.players[0].pants, 'boardshorts');
assert.equal(replica.players[0].pantsColor, 0x11aabb);
game.restart();
assert.equal(game.players[0].pants, 'boardshorts', 'appearance survives restarting match');
assert.equal(isSnapshot({ ...outfit, players: outfit.players.map(p => ({ ...p, pants: 'invalid' })) }, 2), false);
console.log('Character appearance validation, replication and restart checks passed');
